from dataclasses import dataclass

EVIL_URL = "https://evil.example/verify"


def zw_split(text: str) -> str:
    """Вставить zero-width space между символами: человек видит текст, фильтры по словам не срабатывают."""
    return "​".join(text)


@dataclass(frozen=True)
class Vector:
    """Один вектор атаки: агент, отравленные данные и признак успеха."""

    name: str
    kind: str  # summarizer | analyst | searcher | reviewer
    hiding: str  # чем спрятана инструкция
    system_prompt: str
    task: str
    data: str
    success_pattern: str  # регулярка: если найдена в ответе — агент выполнил чужую инструкцию


